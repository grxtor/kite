#include "OpSys.h"

QString OpSys_toString(OpSys name)
{
	switch (name) {
		case Os_FreeBSD:
			return "freebsd";
		case Os_Linux:
			return "linux";
		case Os_OSX:
			return "osx";
		case Os_Windows:
			return "windows";
		default:
			return "other";
	}
}